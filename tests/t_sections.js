const {load,SEED}=require('./harness');
const ok=(condition,message)=>console.log(`  ${condition?'✅':'❌'} ${message}`);

console.log('=== SECTIONS. Separate records, memberships, and inherited subjects ===');
let seed=SEED();
seed.curricula=[{program:'BSCS',yearLevel:3,term:'first',subjectCode:'SUB1',subjectName:'HCI',units:3,status:'active'},{program:'BSCS',yearLevel:3,term:'first',subjectCode:'SUB2',subjectName:'SE',units:3,status:'active'}];
seed.users.push({username:'coordinator.demo',role:'coordinator',status:'active'});
seed.sections=[{id:'A',name:'1',program:'BSCS',yearLevel:1,sectionNumber:1,capacity:50}];
let r=load('coordinator.html',{...seed,currentUser:{username:'coordinator.demo',role:'coordinator'}});
ok(r.read('sections').some(section=>section.id==='A'),'legacy student section is migrated to a section record');
ok(!!r.d.querySelector('#sectionManagementSection .section-add'),'Section Add action belongs to the Coordinator workspace');
ok(r.d.querySelectorAll('#coordinatorSectionTable .section-command-trigger').length===r.read('sections').length,'each section keeps one hidden right-click action menu');
const sectionMenu=r.d.querySelector('#coordinatorSectionTable .section-command-menu');
ok(!!sectionMenu&&/Assign subjects/.test(sectionMenu.textContent)&&/Edit section/.test(sectionMenu.textContent)&&/Delete section/.test(sectionMenu.textContent),'section settings menu names all existing actions');
ok(!r.d.querySelector('body[data-role="admin"]'),'Section Management runs under the Coordinator role');
r.w.SectionManagement.create();
ok(r.d.getElementById('sectionCapacity').value==='50','new sections default to a 50-student limit');
r.d.getElementById('sectionProgram').value='BSCS';
r.d.getElementById('sectionYear').value='3';
r.d.getElementById('sectionNumber').value='2';
r.d.getElementById('sectionCapacity').value='35';
r.d.getElementById('sectionForm').dispatchEvent(new r.w.Event('submit',{bubbles:true,cancelable:true}));
ok(r.read('sections').some(section=>section.id==='3BSCS-2'&&section.program==='BSCS'&&section.yearLevel===3&&section.sectionNumber===2&&section.capacity===35),'new section stores its ID, year, curriculum, section number, and student capacity');
const headings=[...r.d.querySelectorAll('#coordinatorSectionTable th')].map(cell=>cell.textContent.trim());
ok(headings.join('|')==='Unique ID|Year Level|Curriculum|Section|Count','section table removes its visible Actions column');
const savedRow=[...r.d.querySelectorAll('#coordinatorSectionTable tr')].find(row=>row.cells[0]?.textContent.includes('3BSCS-2'));
savedRow.dispatchEvent(new r.w.MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:40,clientY:40}));
ok(savedRow.querySelector('.section-command-menu').classList.contains('open'),'right-clicking a section opens its navigation prompt');
ok([...r.d.getElementById('sectionProgram').options].map(option=>option.value).join('|')==='BSCS|BSIT|BSIS|BSGAMEDEV|BSANIMATION','curriculum choices include BSCS, BSIT, BSIS, Game Development, and Digital Animation');
ok(savedRow&&savedRow.cells[1].textContent==='3'&&savedRow.cells[2].textContent==='BSCS'&&savedRow.cells[3].textContent==='2'&&savedRow.cells[4].textContent.trim().startsWith('0/35'),'3BSCS-2 displays its academic details and student count over limit');
 r.w.SectionManagement.edit(r.read('sections').findIndex(section=>section.id==='3BSCS-2'));
ok(r.d.getElementById('sectionCapacity').value==='35','Edit section exposes the current student limit');
r.w.SectionManagement.close('sectionEditorDialog');
ok(!!r.d.getElementById('sectionProgramFilter'),'Section Management offers curriculum filtering');

const before=r.read('sections').length;
r.w.SectionManagement.create();r.d.getElementById('sectionProgram').value='BSCS';r.d.getElementById('sectionYear').value='3';r.d.getElementById('sectionNumber').value='2';r.d.getElementById('sectionForm').dispatchEvent(new r.w.Event('submit',{bubbles:true,cancelable:true}));
ok(r.read('sections').length===before,'duplicate section ID is rejected');

r.w.SectionManagement.assign(r.read('sections').findIndex(section=>section.id==='3BSCS-2'));
const subjectChecks=[...r.d.querySelectorAll('#sectionSubjectList select[data-subject]')];
ok(subjectChecks.length===2,'section editor lists the active Subject Management curriculum subjects');
subjectChecks.forEach(select=>select.value='F1');
r.w.SectionManagement.saveSubjects();
ok(r.read('sectionSubjects')[0].assignments.length===2&&r.read('sectionSubjects')[0].assignments.every(item=>item.facultyId==='F1'),'multiple subject offerings with professors are saved to one section');
r.w.close();

seed=SEED(); seed.allotments=[]; seed.sections=[{id:'A',name:'Section A'}];
seed.sectionSubjects=[{sectionId:'A',subjectCodes:['SUB2']}];
r=load('student.html',{...seed,currentUser:{username:'S1',role:'student'}});
ok(r.d.getElementById('statSubjects').textContent==='1','student inherits the section subject without a direct allotment');
ok(r.d.getElementById('subjectsTable').textContent.includes('SUB2'),'inherited subject appears in the student subject list');
ok(r.d.getElementById('examTable').textContent.includes('F2 SECRET Exam'),'exam for inherited subject is visible');
r.w.close();
process.exit(0);
