const {load,SEED}=require('./harness');
const ok=(c,m)=>console.log(`  ${c?'✅':'❌'} ${m}`);

(async()=>{
console.log('=== EXAM WORKSPACE. Create opens the question list with the settings column ===');
const seed=SEED();
seed.sections=[{id:'A'}];
seed.sectionSubjects=[{sectionId:'A',assignments:[{id:'A_SUB1',subjectCode:'SUB1',facultyId:'F1'}]}];
const r=load('faculty.html',{...seed,currentUser:{username:'F1',role:'faculty'}});
const panel=r.d.getElementById('examModal');
ok(!!panel.closest('.exam-workspace-shell')&&!panel.closest('#examsView'),'exam settings live beside the question list, outside the re-rendered view');

r.w.openExamModal('SUB1');
ok(!!r.d.querySelector('#examsView .question-workspace.is-new-exam'),'Create exam opens the question workspace');
ok(panel.classList.contains('active'),'settings column starts expanded for a new exam');
ok(/No questions yet/.test(r.d.getElementById('examsView').textContent),'new exam shows an empty question list');
const gear=r.d.querySelector('#examsView .exam-settings-btn');
ok(gear.getAttribute('aria-expanded')==='true','gear reports the open settings column');
r.d.getElementById('examTitle').value='Workspace quiz';
r.d.getElementById('examTitle').dispatchEvent(new r.w.Event('input',{bubbles:true}));
ok(r.d.getElementById('questionWorkspaceTitle').textContent==='Workspace quiz','list heading follows the exam title');
await r.w.toggleExamSettings();
ok(!panel.classList.contains('active')&&!!r.d.querySelector('#examsView .is-new-exam'),'gear collapses the settings without leaving the new exam');
await r.w.toggleExamSettings();
ok(panel.classList.contains('active'),'gear expands the settings again');

const labelsOf=()=>[...r.d.querySelectorAll('#examsView .question-catalog-actions [aria-label]')].map(b=>b.getAttribute('aria-label'));
ok(['Exam settings','Add question','Import questions (exam file or CSV)','Export examination','Preview examination'].every(l=>labelsOf().includes(l)),'new exam has the same tools as a saved one (settings, add, import, export, preview)');
ok(!r.d.querySelector('#examsView #publishExamBtn'),'publishing waits until the exam is saved');

console.log('\n=== ADD QUESTION. Questions can be added before the settings are filled ===');
const menu=r.d.querySelector('#examsView .question-add-menu');
ok(!!menu&&menu.querySelectorAll('.question-type-nav button').length===8,'"+" offers all eight question types');
ok(await r.w.addQuestionOfType('truefalse')===true,'"+" works with the required settings still empty');
const qModal=r.d.getElementById('questionModal');
ok(qModal.classList.contains('active')&&!qModal.classList.contains('choosing-type'),'question prompt opens directly on the editor');
ok(r.d.getElementById('questionType').value==='truefalse','chosen type is applied');
const body=qModal.querySelector('.authoring-body');
ok(body.querySelector(':scope > .question-canvas')&&body.querySelector(':scope > .question-inspector')&&body.querySelector(':scope > .question-inline-preview'),'prompt has question and settings columns with the preview below');
r.d.getElementById('questionText').value='The sky is blue.';
r.w.saveQuestion();
ok(/The sky is blue/.test(r.d.querySelector('#examsView .question-item')?.textContent||''),'question appears in the new exam list');
ok(!r.read('questions').some(q=>q.text==='The sky is blue.')&&!r.read('exams').some(e=>e.title==='Workspace quiz'),'nothing is stored before the exam is saved');
ok(!Object.keys(r.read('questionDrafts')||{}).some(k=>k.startsWith(r.w.eval('provisionalExamId'))),'drafts of the unsaved exam are not stored either');

console.log('\n=== EXIT. Leaving asks: Cancel, Save as draft, Discard ===');
const tick=()=>new Promise(res=>setTimeout(res,0));
let leaving=r.w.goBackFromQuestionBank();await tick();
ok(r.d.getElementById('saveDiscardTitle')?.textContent==='Leave this new exam?','Back asks before leaving');
ok(['continueEditing','saveChanges','discardChanges'].map(id=>r.d.getElementById(id).textContent).join('|')==='Cancel|Save as draft|Discard','choices are Cancel, Save as draft, Discard');
r.d.getElementById('continueEditing').click();await leaving;
ok(!!r.d.querySelector('#examsView .is-new-exam')&&/The sky is blue/.test(r.d.getElementById('examsView').textContent),'Cancel keeps the new exam and its question');
leaving=r.w.goBackFromQuestionBank();await tick();
r.d.getElementById('saveChanges').click();await leaving;await tick();
ok(!!r.d.querySelector('#examsView .is-new-exam')&&!r.read('exams').some(e=>e.title==='Workspace quiz'),'Save as draft with required settings missing stays and stores nothing');
ok(/fill all required fields/i.test(r.d.body.textContent)&&panel.classList.contains('active'),'missing settings are reported and the settings column opens');
r.w.facultyNav.show('dashboard-tab');await tick();
ok(r.d.getElementById('exams-tab').style.display==='block'&&r.d.getElementById('saveDiscardTitle'),'leaving through the sidebar also asks first');
r.d.getElementById('continueEditing').click();await tick();
ok(!!r.d.querySelector('#examsView .is-new-exam'),'Cancel from the sidebar prompt stays on the new exam');

console.log('\n=== SAVE. Saving needs the required settings and stores the exam with its questions ===');
r.d.getElementById('examDate').value='2026-11-04';
r.d.getElementById('examStart').value='09:00';
r.d.getElementById('examEnd').value='10:00';
ok(await r.w.saveExam()===true,'Save Exam succeeds once required settings are filled');
const created=r.read('exams').find(e=>e.title==='Workspace quiz');
ok(created&&created.status==='draft','exam stored as a draft');
ok(r.read('questions').some(q=>q.examId===created.id&&q.text==='The sky is blue.'),'questions added before saving are stored with it');
ok(!!r.d.querySelector('#examsView .question-workspace:not(.is-new-exam)')&&/Question bank/.test(r.d.getElementById('examsView').textContent),'workspace becomes the saved exam\'s question bank');
const item=r.d.querySelector('#examsView .question-item');

console.log('\n=== EDIT. Clicking a question opens it in the prompt ===');
item.click();
ok(qModal.classList.contains('active')&&r.d.getElementById('questionText').value==='The sky is blue.','clicking a list row opens that question');
r.w.closeQuestionModal();
r.d.querySelector('#examsView .question-more summary').click();
ok(!qModal.classList.contains('active'),'the row menu does not open the editor');

console.log('\n=== EXISTING EXAM. Gear opens the settings beside the list ===');
r.w.manageQuestions('e1');
ok(!panel.classList.contains('active'),'opening another exam starts with settings collapsed');
r.d.querySelector('#examsView .exam-settings-btn').click();
ok(panel.classList.contains('active')&&r.d.getElementById('examModalTitle').textContent==='Edit Exam','gear expands the exam settings');
ok(!!r.d.querySelector('#examsView .question-workspace')&&r.d.querySelectorAll('#examsView .question-item').length===2,'question list stays visible');
await r.w.collapseExamSettings();
ok(!panel.classList.contains('active')&&!!r.d.querySelector('#examsView .question-workspace'),'collapsing keeps the question list');

console.log('\n=== CANCEL. Cancelling a new exam leaves without saving ===');
const before=r.read('exams').length;
r.w.openExamModal('SUB1');
await r.w.closeExamModal(true);
ok(!r.d.querySelector('#examsView .is-new-exam')&&r.read('exams').length===before,'Cancel returns from the workspace and stores nothing');
r.w.openExamModal('SUB1');
await r.w.addQuestionOfType('short');r.d.getElementById('questionText').value='Throwaway';r.w.saveQuestion();
let closing=r.w.closeExamModal();await new Promise(res=>setTimeout(res,0));
r.d.getElementById('discardChanges').click();await closing;
ok(!r.w.eval('exams').some(e=>e.provisional)&&!r.w.eval('questions').some(q=>q.text==='Throwaway')&&r.read('exams').length===before,'Discard drops the new exam and its questions everywhere');
r.w.openExamModal('SUB1');
r.d.getElementById('examTitle').value='Saved on exit';r.d.getElementById('examTitle').dispatchEvent(new r.w.Event('input',{bubbles:true}));
r.d.getElementById('examDate').value='2026-11-05';r.d.getElementById('examStart').value='09:00';r.d.getElementById('examEnd').value='10:00';
r.w.facultyNav.show('dashboard-tab');await new Promise(res=>setTimeout(res,0));
r.d.getElementById('saveChanges').click();await new Promise(res=>setTimeout(res,20));
ok(r.read('exams').some(e=>e.title==='Saved on exit')&&r.d.getElementById('dashboard-tab').style.display==='block','Save as draft from the sidebar prompt saves, then opens the requested page');

console.log('\n=== COURSE EDITOR. The caller is told when the Professor goes back ===');
let done=0;
r.w.openExamModal('SUB1',()=>done++);
r.w.goBackFromQuestionBank();
ok(done===1,'going back notifies the course editor once');
r.w.openExamModal('SUB1',()=>done++);
r.w.facultyNav.show('dashboard-tab');
ok(done===2,'leaving through the sidebar also returns control to the course editor');
ok(!panel.classList.contains('active'),'settings column closes when the workspace is left');
r.w.manageQuestions('e1');
ok(done===2,'opening an exam afterwards does not notify again');
r.w.editExam('e1');
r.d.getElementById('examTitle').value='Unsaved change';
r.d.getElementById('examTitle').dispatchEvent(new r.w.Event('input',{bubbles:true}));
r.w.facultyNav.show('dashboard-tab');
ok(/unsaved exam settings were not kept/i.test(r.d.body.textContent)&&r.read('exams').find(e=>e.id==='e1').title==='F1 Exam','leaving with unsaved settings warns and saves nothing');
r.w.close();

console.log('\n=== PERMISSIONS. Turned-off actions stay hidden; question rows stay visible ===');
const denied=SEED();
denied.pagePermissions={rules:{'system:faculty':{'prof.questions.edit':'deny','prof.exams.edit':'deny'},'system:professor':{'prof.questions.edit':'deny','prof.exams.edit':'deny'}}};
const p=load('faculty.html',{...denied,currentUser:{username:'F1',role:'faculty'}});
await new Promise(res=>setTimeout(res,20));
p.w.PagePermissions.apply();
p.w.manageQuestions('e1');
const shown=el=>!!el&&p.w.getComputedStyle(el).display!=='none';
ok([...p.d.querySelectorAll('#examsView .question-item')].filter(shown).length===2,'question rows remain visible when writing questions is off');
ok(!shown(p.d.querySelector('#examsView .question-add-menu')),'"+" menu is hidden when writing questions is off');
ok(!shown(p.d.querySelector('#examsView .exam-settings-btn')),'gear is hidden when editing exams is off');
p.d.querySelector('#examsView .question-item').click();
ok(!p.d.getElementById('questionModal').classList.contains('active')&&/Write questions is turned off/.test(p.d.body.textContent),'clicking a row explains the permission instead of opening the editor');
p.w.close();
process.exit(0);
})();
