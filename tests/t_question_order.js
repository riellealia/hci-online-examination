const {load,SEED}=require('./harness');
const ok=(c,m)=>console.log(`  ${c?'✅':'❌'} ${m}`);
const today=new Date().toLocaleDateString('en-CA');
const ids=n=>[...Array(n).keys()].map(i=>`oq${i+1}`);
const manyQuestions=(examId,n)=>ids(n).map((id,i)=>({id,examId,type:'mcq',text:`Item ${i+1}`,points:1,options:[{text:'A',isCorrect:true},{text:'B',isCorrect:false}]}));

console.log('=== REORDER. Dragging (or arrow keys) saves the order and renumbers ===');
const s=SEED();
s.sections=[{id:'A'}];
s.sectionSubjects=[{sectionId:'A',assignments:[{id:'A_SUB1',subjectCode:'SUB1',facultyId:'F1'}]}];
s.questions=[...s.questions,{id:'other',examId:'e2',type:'essay',text:'Other exam',points:5},{id:'q3',examId:'e1',type:'essay',text:'Third',points:5}];
const r=load('faculty.html',{...s,currentUser:{username:'F1',role:'faculty'}});
r.w.manageQuestions('e1');
const labels=()=>[...r.d.querySelectorAll('#questionList .question-item')].map(row=>row.querySelector('.question-text').textContent.trim());
ok(r.d.querySelectorAll('#questionList .question-drag-handle').length===3,'every question has a drag handle');
ok(/Fixed order/.test(r.d.querySelector('.question-order-bar').textContent),'order bar explains drag-to-reorder');
ok(r.w.reorderExamQuestions(['q3','q1','q2'])===true,'new order is accepted');
ok(labels().join('|')==='Q1: Third|Q2: Q1|Q3: Essay Q','list is redrawn in the new order with new numbers');
const stored=r.read('questions');
ok(stored.filter(q=>q.examId==='e1').map(q=>q.id).join('|')==='q3|q1|q2','new order is saved');
ok(stored.findIndex(q=>q.id==='other')===2,"another exam's question keeps its place");
const firstHandle=r.d.querySelector('#questionList .question-drag-handle');
firstHandle.dispatchEvent(new r.w.KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}));
ok(r.read('questions').filter(q=>q.examId==='e1').map(q=>q.id).join('|')==='q1|q3|q2','Arrow Down on the handle moves the question one place');
ok(r.d.activeElement===r.d.querySelectorAll('#questionList .question-drag-handle')[1],'focus follows the moved question');
firstHandle.click();
ok(!r.d.getElementById('questionModal').classList.contains('active'),'pressing the handle does not open the editor');
ok(r.w.reorderExamQuestions(['q1','q2'])===false&&r.read('questions').filter(q=>q.examId==='e1').length===3,'an incomplete order is rejected without losing questions');
// Live renumbering while a row is moved in the DOM.
const list=r.d.getElementById('questionList');list.insertBefore(list.lastElementChild,list.firstElementChild);r.w.renumberQuestionRows();
ok(labels()[0].startsWith('Q1: Essay Q'),'numbers follow the rows while dragging');
r.w.manageQuestions('e1');

console.log('\n=== SHUFFLE. One switch randomizes the order and removes the numbering ===');
ok(r.w.setQuestionShuffle('e1',true)===true,'shuffle switch saves');
ok(r.read('exams').find(e=>e.id==='e1').shuffleQuestions===true,'exam records shuffleQuestions');
ok(!r.d.querySelector('#questionList .question-number')&&!/Q\d+:/.test(r.d.getElementById('questionList').textContent),'numbering is removed');
ok(!r.d.querySelector('#questionList .question-drag-handle'),'drag handles are removed');
ok(/Shuffled for each student/.test(r.d.querySelector('.question-order-bar').textContent)&&r.d.querySelector('.question-shuffle-toggle input').checked,'order bar shows the shuffled state');
r.w.editExam('e1');
ok(r.d.getElementById('examShuffleQuestions').checked,'exam settings show the same setting');
r.d.getElementById('examShuffleQuestions').checked=false;
r.d.getElementById('examShuffleQuestions').dispatchEvent(new r.w.Event('change',{bubbles:true}));
r.w.saveExam().then(saved=>{
ok(saved===true&&r.read('exams').find(e=>e.id==='e1').shuffleQuestions===false,'turning it off in exam settings saves');
ok(!!r.d.querySelector('#questionList .question-number'),'numbering returns when shuffling is off');
r.w.editExam('e1');
r.w.setQuestionShuffle('e1',true);
ok(r.d.getElementById('examShuffleQuestions').checked&&!r.w.eval('examFormDirty'),'switch keeps an open, unchanged settings form in step without marking it edited');
r.w.close();

console.log('\n=== STUDENT. Each attempt gets its own order, kept on refresh ===');
const studentSeed=(extra={})=>{const t=SEED();t.studentEnrollments=[{studentId:'S1',subjectCode:'SUB1',sectionId:'A'}];
  t.exams=[{id:'e1',facultyId:'F1',subjectCode:'SUB1',title:'Shuffled',date:today,start:'00:01',end:'23:59',shuffleQuestions:true}];
  t.questions=manyQuestions('e1',12);return {...t,...extra,currentUser:{username:'S1',role:'student'}};};
let st=load('student.html',studentSeed());
st.w.startExam('e1');
const order=st.w.eval('activeAttempt').questionOrder;
ok(Array.isArray(order)&&order.length===12&&[...order].sort().join()===[...ids(12)].sort().join(),'attempt stores a full order of the questions');
ok(order.join()!==ids(12).join(),'order differs from the stored order (12 questions)');
ok(st.w.eval('currentExamQuestions').map(q=>q.id).join()===order.join(),'questions are shown in that order');
ok(/Item/.test(st.d.getElementById('examQuestionsContainer').textContent)&&st.d.getElementById('examQuestionsContainer').textContent.includes(`Item ${Number(order[0].slice(2))}`),'first question shown is the first in the shuffled order');
const savedAttempts=st.read('examAttempts');
st.w.close();
st=load('student.html',studentSeed({examAttempts:savedAttempts}));
st.w.startExam('e1');
ok(st.w.eval('currentExamQuestions').map(q=>q.id).join()===order.join(),'resuming keeps the same order');
st.w.close();
const fixed=load('student.html',studentSeed({exams:[{id:'e1',facultyId:'F1',subjectCode:'SUB1',title:'Fixed',date:today,start:'00:01',end:'23:59'}]}));
fixed.w.startExam('e1');
ok(fixed.w.eval('currentExamQuestions').map(q=>q.id).join()===ids(12).join()&&!fixed.w.eval('activeAttempt').questionOrder,'without shuffling, students get the list order');
fixed.w.close();
const a={questionOrder:['oq2','gone','oq1']};
const helper=load('student.html',studentSeed());
const merged=helper.w.orderAttemptQuestions(a,manyQuestions('e1',3),true).map(q=>q.id);
ok(merged.slice(0,2).join()==='oq2,oq1'&&merged.length===3&&merged.includes('oq3'),'removed questions drop out and new ones are added after the seen ones');
helper.w.close();
process.exit(0);
});
